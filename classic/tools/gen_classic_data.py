#!/usr/bin/env python3
# gen_classic_data.py - data the classic (1.12) Skada needs and the 1.12 client cannot give it.
#
# The 1.12 combat log is text: spells come by name only and units by name only. This writes
#   Classic/SpellData.lua  every spell name of the 1.12 Spell.dbc with its school, icon and spell ids
#                          (the highest rank first), for GetSpellInfo(id) and name -> id lookups;
#   Classic/BossData.lua   boss name -> creature id, from the comments of LibBossIDs-1.0, so the
#                          made-up creature GUIDs carry the real ids of the bosses.
# Both are plain Lua 5.0 (marked "lua50: native"), loaded before the rest of Skada.
#
# Usage examples:
#   python gen_classic_data.py                                  # Spell.dbc from {wow_classic_mpq_dir}
#   python gen_classic_data.py C:/local/mpq_classic/Work        # mpq dir positional
#   python gen_classic_data.py --mpq-dir C:/local/mpq_classic/Work --addon ../Addons/Skada
#   python gen_classic_data.py --show-cmd                       # print the equivalent command only

import argparse
import os
import re
import struct
import sys

if os.name == "nt":
    os.system("")  # enables ANSI escape codes in the Windows console

RESET = "\033[0m"


def print_ok(msg):
    print(f"\033[32m{msg}{RESET}")


def print_err(msg):
    print(f"\033[31m{msg}{RESET}")


def print_info(msg):
    print(f"\033[36m{msg}{RESET}")


MPQ_DIR_ENV = "wow_classic_mpq_dir"
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
DEFAULT_ADDON = os.path.join(SCRIPT_DIR, "..", "Addons", "Skada")

# Spell.dbc 1.12.1 (build 5875) fields, see MangosZero DBCStructure.h
SPELL_ID, SPELL_SCHOOL, SPELL_ICON, SPELL_NAME_ENUS, SPELL_RANK_ENUS = 0, 1, 117, 120, 129
ICON_PREFIX = "interface\\icons\\"
SKIPPED_NAME = re.compile(r"^(zz|z\s|test|qa |dnd|\[ph\]|unused|deprecated)", re.I)
RANK_NUMBER = re.compile(r"(\d+)")
NATIVE_HEADER = "-- lua50: native (generated by classic/tools/gen_classic_data.py, do not edit)\n"
BOSS_LINE = re.compile(r"^\s*\[(\d+)\]\s*=\s*true,\s*--\s*(.+?)\s*$")


def read_dbc(path):
    with open(path, "rb") as f:
        data = f.read()
    magic, records, fields, record_size, string_size = struct.unpack_from("<4s4I", data, 0)
    if magic != b"WDBC":
        raise ValueError(f"{path}: not a WDBC file")
    base = 20
    strings = data[base + records * record_size:]

    def string_at(offset):
        end = strings.index(b"\0", offset)
        return strings[offset:end].decode("utf-8", "replace")

    rows = []
    for r in range(records):
        rows.append(struct.unpack_from(f"<{fields}I", data, base + r * record_size))
    return rows, string_at


def spell_lines(mpq_dir):
    icons_rows, icon_str = read_dbc(os.path.join(mpq_dir, "DBFilesClient", "SpellIcon.dbc"))
    icons = {}
    for row in icons_rows:
        path = icon_str(row[1])
        if path.lower().startswith(ICON_PREFIX):
            path = path[len(ICON_PREFIX):]
        icons[row[0]] = path

    rows, string_at = read_dbc(os.path.join(mpq_dir, "DBFilesClient", "Spell.dbc"))
    by_name = {}
    for row in rows:
        name = string_at(row[SPELL_NAME_ENUS]).strip()
        if not name or SKIPPED_NAME.match(name) or "\t" in name or "\n" in name or "#" in name:
            continue
        rank = string_at(row[SPELL_RANK_ENUS])
        m = RANK_NUMBER.search(rank)
        by_name.setdefault(name, []).append((int(m.group(1)) if m else 0, row[SPELL_ID], row[SPELL_SCHOOL], icons.get(row[SPELL_ICON], "")))

    lines = []
    for name in sorted(by_name):
        spells = by_name[name]
        # the highest rank first (ties: the lowest id), it is the id the name stands for
        spells.sort(key=lambda s: (-s[0], s[1]))
        _, _, school, icon = spells[0]
        if not icon:
            icon = next((s[3] for s in spells if s[3]), "")
        ids = "#".join(str(s[1]) for s in spells)
        lines.append(f"{name}\t{1 << school if school < 7 else 1}\t{icon}\t#{ids}#")
    return lines


def write_spell_data(addon, lines):
    data = "\n" + "\n".join(lines) + "\n"
    if "]]" in data or "[[" in data:
        raise ValueError("spell data contains [[ or ]]")
    out = os.path.join(addon, "Classic", "SpellData.lua")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(NATIVE_HEADER)
        f.write("-- one line per spell name: name <tab> school mask <tab> icon <tab> #id#id#...# (highest rank first)\n")
        f.write('rawset(SkadaEnv, "SKADA_SPELL_DATA", [[' + data + ']])\n')
    return out


def write_boss_data(addon):
    lib = os.path.join(addon, "Libs", "LibBossIDs-1.0", "LibBossIDs-1.0.lua")
    bosses = {}
    with open(lib, encoding="utf-8", errors="replace") as f:
        for line in f:
            m = BOSS_LINE.match(line)
            if m:
                name = m.group(2).strip('"')
                bosses.setdefault(name, int(m.group(1)))
    out = os.path.join(addon, "Classic", "BossData.lua")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(NATIVE_HEADER)
        f.write("-- boss name -> creature id (LibBossIDs-1.0's comments), for the made-up creature GUIDs\n")
        f.write('rawset(SkadaEnv, "SKADA_BOSS_IDS", {\n')
        for name in sorted(bosses):
            f.write(f'\t["{name.replace(chr(92), chr(92) * 2).replace(chr(34), chr(92) + chr(34))}"] = {bosses[name]},\n')
        f.write("})\n")
    return out, len(bosses)


def main():
    ap = argparse.ArgumentParser(description="Generate the classic Skada spell and boss data.")
    ap.add_argument("mpq_pos", nargs="?", help="extracted classic MPQ dir (positional)")
    ap.add_argument("--mpq-dir", dest="mpq_opt", help=f"extracted classic MPQ dir (default: {{{MPQ_DIR_ENV}}})")
    ap.add_argument("--addon", default=DEFAULT_ADDON, help="the classic Skada addon dir")
    ap.add_argument("--show-cmd", action="store_true", help="print the equivalent command, run nothing")
    args = ap.parse_args()
    mpq_dir = args.mpq_opt or args.mpq_pos or os.environ.get(MPQ_DIR_ENV)
    if args.show_cmd:
        print(f'python "{sys.argv[0]}" --mpq-dir "{mpq_dir}" --addon "{args.addon}"')
        return 0
    if not mpq_dir:
        print_err(f"no MPQ dir: pass one or set {MPQ_DIR_ENV}")
        return 1

    os.makedirs(os.path.join(args.addon, "Classic"), exist_ok=True)
    lines = spell_lines(mpq_dir)
    out = write_spell_data(args.addon, lines)
    print_info(f"{len(lines)} spell names -> {out}")
    out, count = write_boss_data(args.addon)
    print_info(f"{count} bosses -> {out}")
    print_ok("done")
    return 0


if __name__ == "__main__":
    sys.exit(main())
